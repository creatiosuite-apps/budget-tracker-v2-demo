export function t(
  key: TranslationKey | string,
  lang: LanguageCode = 'en',
  vars?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] as Record<string, string> | undefined;
  const enDict = TRANSLATIONS.en as Record<string, string>;
  let template = dict?.[key] ?? enDict[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      template = template.replace(
        new RegExp(`\\{\\{${k}\\}\\}`, 'g'),
        String(v)
      );
    });
  }
  return template;
}

export function formatMonthYearLabel(
  ym: string,
  lang: LanguageCode = 'en',
  monthStyle: 'short' | 'long' = 'short'
): string {
  const [yStr, mStr] = ym.split('-');
  const y = parseInt(yStr, 10) || 2026;
  const m = parseInt(mStr, 10) || 11;
  return new Date(y, m - 1, 1).toLocaleDateString(getLocaleForLanguage(lang), {
    month: monthStyle,
    year: 'numeric',
  });
}

export function formatMonthOnlyName(
  monthNumZeroBased: number,
  lang: LanguageCode = 'en',
  style: 'short' | 'long' = 'short'
): string {
  return new Date(2026, monthNumZeroBased, 1).toLocaleDateString(
    getLocaleForLanguage(lang),
    { month: style }
  );
}

export function getLocalizedWeekdays(
  lang: LanguageCode = 'en'
): { short: string; narrow: string }[] {
  const locale = getLocaleForLanguage(lang);
  // 2026-11-01 is a Sunday
  return Array.from({ length: 7 }, (_, i) => {
    const dt = new Date(2026, 10, 1 + i);
    return {
      short: dt.toLocaleDateString(locale, { weekday: 'short' }),
      narrow: dt.toLocaleDateString(locale, { weekday: 'narrow' }),
    };
  });
}

export function getLocalizedGroupLabel(
  group: 'All' | 'Needs' | 'Wants' | 'Savings' | 'Income' | string,
  lang: LanguageCode = 'en'
): string {
  switch (group) {
    case 'All':
      return t('groupAll', lang);
    case 'Needs':
      return t('groupNeeds', lang);
    case 'Wants':
      return t('groupWants', lang);
    case 'Savings':
      return t('groupSavings', lang);
    case 'Income':
      return t('groupIncome', lang);
    default:
      return group;
  }
}

export function getTimeGreetingText(
  userName: string | undefined,
  lang: LanguageCode = 'en'
): string {
  const hour = new Date().getHours();
  let greetingKey: TranslationKey = 'goodNight';
  if (hour >= 5 && hour < 12) {
    greetingKey = 'goodMorning';
  } else if (hour >= 12 && hour < 17) {
    greetingKey = 'goodAfternoon';
  } else if (hour >= 17 && hour < 21) {
    greetingKey = 'goodEvening';
  }

  const greeting = t(greetingKey, lang);
  const trimmedName = (userName || '').trim();
  // Custom user name is NEVER translated — preserved verbatim
  return trimmedName
    ? `${greeting}, ${trimmedName}`
    : `${greeting}, ${t('welcomeBack', lang)}`;
}

export function getFormattedTodayDateText(lang: LanguageCode = 'en'): string {
  return new Date().toLocaleDateString(getLocaleForLanguage(lang), {
    weekday: 'long',
    month: 'short',
    day: 'numeric',
  });
}
